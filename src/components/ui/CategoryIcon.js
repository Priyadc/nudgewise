/** Coloured rounded icon for a category. Pass `meta` to render an unsaved/custom one directly. */
export default function CategoryIcon({ name, meta, size = 38 }) {
  const m = meta || categoryMeta(name);
  const Icon = ICONS[m.icon] || CircleDashed;
  return (
    <span className="cat-icon" style={{ width: size, height: size, background: `${m.color}22`, color: m.color }}>
      <Icon />
    </span>
  );
}
